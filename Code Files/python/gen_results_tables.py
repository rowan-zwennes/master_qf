def _resolve(base: Path, run: str) -> Path:
    """New root if the cell is there, else the aux root it was produced in."""
    p = base / run
    if p.is_dir():
        return p
    alt = AUX_FALLBACK.get(run)
    return (NAS_AUX / alt) if alt else p
LOT = 0.005


def daily_series(run: Path, sid: int) -> dict[str, np.ndarray]:
    files = sorted(glob.glob(str(run / f"s{sid}" / "summary_*.json")))
    if not files:
        raise FileNotFoundError(run / f"s{sid}")
    rows = [json.load(open(f)) for f in files]
    return {
        "pnl": np.array([r["terminal_pnl"] for r in rows]),
        "fills": np.array([r["n_fills"] for r in rows], dtype=float),
        "absq": np.array([r["mean_abs_inv"] for r in rows]) / LOT,
    }


def markout_5s(run: Path, sid: int) -> float:
    """Mean per-fill 5 s markout in bps, pooled over every day of a run cell."""
    mo = []
    for f in sorted(glob.glob(str(run / f"s{sid}" / "fills_*.parquet"))):
        d = pl.read_parquet(f).filter(~pl.col("is_liquidation"))
        px = d["price"].to_numpy()
        side = d["side"].to_numpy().astype(float)
        m0, m5 = d["mid_0s"].to_numpy(), d["mid_5s"].to_numpy()
        ok = np.isfinite(m0) & np.isfinite(m5)
        mo.append(1e4 * (side * (m5 - px) / px)[ok])
    if not mo:
        raise FileNotFoundError(run / f"s{sid}" / "fills_*.parquet")
    return float(np.concatenate(mo).mean())


def es5(pnl: np.ndarray) -> float:
    k = max(1, int(0.05 * len(pnl)))
    return float(np.sort(pnl)[:k].mean())


def row_stats(d: dict[str, np.ndarray], seed: int) -> dict:
    ci = block_bootstrap_ci(d["pnl"], sharpe_ratio, seed=seed)
    return {
        "sharpe": sharpe_ratio(d["pnl"]), "ci_lo": ci.lo, "ci_hi": ci.hi,
        "mean": d["pnl"].mean(), "sd": d["pnl"].std(ddof=1),
        "worst": d["pnl"].min(), "es5": es5(d["pnl"]),
        "cpf": 100.0 * d["pnl"].sum() / d["fills"].sum(),
        "fills": d["fills"].mean(), "absq": d["absq"].mean(),
    }


def fmt_row(label: str, s: dict) -> str:
    return (f"{label} & {s['sharpe']:.1f} & [{s['ci_lo']:.1f}, {s['ci_hi']:.1f}]"
            f" & {s['mean']:,.0f} & {s['sd']:,.0f} & {s['cpf']:.2f}"
            f" & {s['es5']:,.0f} & {s['fills']:,.0f} & {s['absq']:.2f} \\\\")


def main_table(base: Path, rep: Path) -> None:
    spec = [
        ("1 Naive (matched)", "ablation_h10_qa_naive_matched", 1),
        ("2 GLT",                          "ablation_h10_qa", 2),
        ("3 GLT $+$ AR",                   "ablation_h10_qa", 3),
        ("4 GLT $+$ ML",                   "ablation_h10_qa", 4),
        ("5 GLT $+$ funding",              "ablation_h10_qa", 5),
        ("6 Hybrid",      "ablation_h10_qa", 6),
    ]
    lines = [
        "% generated by gen_results_tables.py",
        r"\begin{tabular}{lrcrrrrrr}", r"\toprule",
        (r"Strategy & Sharpe & 95\% CI & Mean/d & SD/d & Net/fill (\textcent) & ES$_{5\%}$ & "
         r"Fills/d & $\overline{|q|}$ \\"), r"\midrule",
    ]
    seeds = {("ablation_h10_qa_naive_matched", 1): 1 + 100 * 1,
             ("ablation_h10_qa", 2): 2 + 100 * 2,
             ("ablation_h10_qa", 3): 3 + 100 * 4,
             ("ablation_h10_qa", 4): 4 + 100 * 5,
             ("ablation_h10_qa", 5): 5 + 100 * 3,
             ("ablation_h10_qa", 6): 6 + 100 * 6}
    for i, (label, run, sid) in enumerate(spec):
        if i == 1:
            lines.append(r"\addlinespace")
        d = daily_series(base / run, sid)
        lines.append(fmt_row(label, row_stats(d, seed=seeds[(run, sid)])))
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    (rep / "tab_results_main.tex").write_text("\n".join(lines))


def couplings_table(base: Path, rep: Path) -> None:
    """Horizon vs defensive, both signal strategies, GLT as the reference row."""
    spec = [
        ("2 GLT (reference)", "ablation_h10_qa", 2, None),
        ("3 GLT $+$ AR (horizon)", "ablation_h10_qa", 3,
         "ablation_h10_qa_horizon_placebo"),
        ("3 GLT $+$ AR (defensive)", "ablation_h10_qa_defensive", 3,
         "ablation_h10_qa_defensive_placebo"),
        ("4 GLT $+$ ML (horizon)", "ablation_h10_qa", 4,
         "ablation_h10_qa_horizon_placebo"),
        ("4 GLT $+$ ML (defensive)", "ablation_h10_qa_defensive", 4,
         "ablation_h10_qa_defensive_placebo"),
    ]
    lines = [
        "% generated by gen_results_tables.py",
        r"\begin{tabular}{lrrrrrrr}", r"\toprule",
        (r"Strategy / coupling & Mean/d & SD/d & ES$_{5\%}$ & Fills/d & "
         r"$\overline{|q|}$ & mo$_{5\text{s}}$ (bp) & $\Delta$ placebo \\"),
        r"\midrule",
    ]
    for j, (label, run, sid, plc) in enumerate(spec):
        if j in (1, 3):
            lines.append(r"\addlinespace")
        d = daily_series(base / run, sid)
        mo5 = markout_5s(base / run, sid)
        if plc is None:
            dplc = "---"
        else:
            q = daily_series(base / plc, sid)
            dplc = f"{(d['pnl'] - q['pnl']).mean():+,.0f}"
        lines.append(
            f"{label} & {d['pnl'].mean():,.0f} & {d['pnl'].std(ddof=1):,.0f}"
            f" & {es5(d['pnl']):,.0f} & {d['fills'].mean():,.0f}"
            f" & {d['absq'].mean():.2f} & {mo5:.3f} & {dplc} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    (rep / "tab_results_couplings.tex").write_text("\n".join(lines))


def placebo_table(base: Path, rep: Path) -> None:
    lines = [
        "% generated by gen_results_tables.py",
        r"\begin{tabular}{lrrrrl}", r"\toprule",
        (r"Coupling, strategy & Real mean/d & Placebo mean/d & Real fills/d & "
         r"Placebo fills/d & $\Delta$ (real $-$ placebo) \\"), r"\midrule",
    ]
    for mode, real_run, plc_run in [
        ("Horizon", "ablation_h10_qa", "ablation_h10_qa_horizon_placebo"),
        ("Defensive", "ablation_h10_qa_defensive",
         "ablation_h10_qa_defensive_placebo"),
    ]:
        for j, (sid, sname) in enumerate([(3, "AR"), (4, "ML"), (6, "Hybrid")]):
            try:
                r = daily_series(base / real_run, sid)
                q = daily_series(base / plc_run, sid)
            except FileNotFoundError:
                continue
            if j == 0 and mode != "Horizon":
                lines.append(r"\addlinespace")
            diff = r["pnl"] - q["pnl"]
            ci = block_bootstrap_ci(diff, np.mean, seed=7 + 10 * sid)
            t = diff.mean() / (diff.std(ddof=1) / np.sqrt(len(diff)))
            lines.append(
                f"{mode}, {sname} & {r['pnl'].mean():,.0f} & "
                f"{q['pnl'].mean():,.0f} & "
                f"{r['fills'].mean():,.0f} & {q['fills'].mean():,.0f} & "
                f"${diff.mean():+,.0f}$ [{ci.lo:,.0f}, {ci.hi:,.0f}], "
                f"$t = {t:.1f}$ \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    (rep / "tab_results_placebo.tex").write_text("\n".join(lines))


def frontier_figure(base: Path, rep: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fam: dict[str, list] = {"naive": [], "mlhor": [], "arhor": []}
    cells = (
        [(f"frontier/naive_hs{t}", 1, "naive", lab) for t, lab in
         [("5", "5"), ("8p6", "8.6"), ("12", "12"), ("16", "16"), ("20", "20")]]
        + [(f"frontier/naive_hs{t}", 1, "naive", t)
           for t in ("25", "30", "40")]
        + [(f"frontier_hor/mlhor_h{h}", 4, "mlhor", h) for h in (5, 10, 20, 40)]
        + [(f"frontier_hor/arhor_h{h}", 3, "arhor", h) for h in (5, 10, 20, 40)]
    )
    for run, sid, family, lab in cells:
        try:
            d = daily_series(_resolve(base, run), sid)
        except FileNotFoundError:
            continue
        fam[family].append((d["fills"].mean(), d["pnl"].mean(),
                            d["absq"].mean(), str(lab)))
    glt = daily_series(base / "ablation_h10_qa", 2)

    plt.rcParams.update({"font.size": 8.5, "axes.labelsize": 8.5,
                         "xtick.labelsize": 8, "ytick.labelsize": 8,
                         "legend.fontsize": 8.5})
    style = {"naive": ("tab:gray", "o", "Naive width family (hs $40 \\to 5$ USDT per BTC)"),
             "mlhor": ("tab:red", "s", "ML horizon ($h$ $5 \\to 40$ s)"),
             "arhor": ("tab:green", "^", "AR horizon ($h$ $5 \\to 40$ s)")}
    fig, axes = plt.subplots(1, 2, figsize=(6.3, 2.2))
    for family, pts in fam.items():
        if not pts:
            continue
        pts.sort()
        f, pnl, q, labs = zip(*pts)
        c, m, lab = style[family]
        axes[0].plot(f, pnl, marker=m, color=c, lw=1.4, ms=4, label=lab)
        axes[1].plot(f, q, marker=m, color=c, lw=1.4, ms=4, label=lab)
    for ax, y in ((axes[0], glt["pnl"].mean()), (axes[1], glt["absq"].mean())):
        ax.plot(glt["fills"].mean(), y, marker="*", color="tab:blue", ms=11,
                ls="none", label="GLT (s2)")
    try:
        fa = daily_series(_resolve(base, "feeaware/feeaware_s2"), 2)
        for ax, y in ((axes[0], fa["pnl"].mean()), (axes[1], fa["absq"].mean())):
            ax.plot(fa["fills"].mean(), y, marker="D", color="tab:purple",
                    ms=6, ls="none", label="GLT (fee-aware)")
    except FileNotFoundError:
        pass
    axes[0].set_ylabel("mean daily P&L (USDT)")
    axes[1].set_ylabel("mean $|q|$ (lots)")
    for ax in axes:
        ax.set_xlabel("fills / day")
        ax.grid(alpha=0.25, lw=0.5)
    axes[0].set_xlim(-1000, 20000)
    axes[1].set_xlim(-800, 16000)
    handles, labels = axes[1].get_legend_handles_labels()
    fig.legend(handles, labels, ncol=3, loc="lower center",
               bbox_to_anchor=(0.5, 0.97), frameon=False,
               handlelength=1.4, columnspacing=1.0)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(rep / f"fig_frontier.{ext}", dpi=200, bbox_inches="tight")
    plt.close(fig)


